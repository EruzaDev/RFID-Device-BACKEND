create table if not exists public.devices (
  id text primary key check (id ~ '^[A-Za-z0-9_-]{1,64}$'),
  secret text not null check (secret ~ '^[0-9a-f]{64}$'),
  active boolean not null default true
);

create table if not exists public.students (
  uid text primary key check (uid ~ '^([0-9A-F]{8}|[0-9A-F]{14}|[0-9A-F]{20})$'),
  name text not null check (length(trim(name)) > 0),
  active boolean not null default true
);

create table if not exists public.items (
  uid text primary key check (uid ~ '^([0-9A-F]{8}|[0-9A-F]{14}|[0-9A-F]{20})$'),
  name text not null check (length(trim(name)) > 0),
  active boolean not null default true
);

create table if not exists public.loans (
  id bigint generated by default as identity primary key,
  student_uid text not null references public.students(uid),
  item_uid text not null references public.items(uid),
  borrowed_at timestamptz not null default now(),
  returned_at timestamptz,
  borrow_device text not null references public.devices(id),
  return_device text references public.devices(id)
);

create unique index if not exists one_open_loan_per_item
  on public.loans(item_uid) where returned_at is null;
create index if not exists loans_student_open_idx
  on public.loans(student_uid) where returned_at is null;

create table if not exists public.nonces (
  device_id text not null references public.devices(id),
  nonce text not null check (nonce ~ '^[0-9a-f]{32}$'),
  seen_at timestamptz not null default now(),
  primary key (device_id, nonce)
);
create index if not exists nonces_seen_at_idx on public.nonces(seen_at);

create table if not exists public.requests (
  device_id text not null references public.devices(id),
  request_id text not null check (request_id ~ '^[0-9a-f]{32}$'),
  body_hash text not null check (body_hash ~ '^[0-9a-f]{64}$'),
  response jsonb not null,
  primary key (device_id, request_id)
);

create table if not exists public.device_state (
  device_id text primary key references public.devices(id),
  mode text not null check (mode in ('borrow', 'return')),
  stage text not null check (stage in ('idle', 'scan_student', 'scan_item', 'confirm', 'success', 'error')),
  updated_at bigint not null
);

-- The Edge Function is the only API for these tables. Its direct database
-- connection checks device HMAC signatures before writing anything.
alter table public.devices enable row level security;
alter table public.students enable row level security;
alter table public.items enable row level security;
alter table public.loans enable row level security;
alter table public.nonces enable row level security;
alter table public.requests enable row level security;
alter table public.device_state enable row level security;

revoke all on public.devices, public.students, public.items, public.loans,
  public.nonces, public.requests, public.device_state from anon, authenticated;

-- Process state contains only device ID, mode, stage, and timestamp. It can be
-- streamed to an anonymous kiosk without exposing cards, loans, or secrets.
grant select on public.device_state to anon;
create policy "Public scanner process state" on public.device_state
  for select to anon using (true);

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'device_state'
  ) then
    if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
      alter publication supabase_realtime add table public.device_state;
    else
      create publication supabase_realtime for table public.device_state;
    end if;
  end if;
end $$;
